"""PlatformIO C++17 Firmware Synthesizer with Decoupled HAL & Native TDD."""

from __future__ import annotations

import re
import shutil
from pathlib import Path

from contracts.hw_models import EmbeddedProjectSpec, HardwareBlueprint

_TEMPLATES_DIR = Path(__file__).resolve().parent / "hal_templates"

ARCHETYPE_ENUM_MAP = {
    "microclimate_pid": "ehil::Archetype::MICROCLIMATE_PID",
    "rover_obstacle_fsm": "ehil::Archetype::ROVER_OBSTACLE_FSM",
    "edge_voice_display": "ehil::Archetype::EDGE_VOICE_DISPLAY",
}


def _c_ident(text: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", text).upper()
    return cleaned if not cleaned[0].isdigit() else f"P_{cleaned}"


def _render_platformio_ini(blueprint: HardwareBlueprint) -> str:
    b = blueprint.board
    return f"""; Auto-generated by Embedded Hardware Architect & Serial HIL Studio
; Project: {blueprint.project_name} ({blueprint.project_id})
[platformio]
default_envs = native

[env:native]
platform = native
build_flags =
    -std=c++17
    -Wall
    -Wextra
    -Werror
    -Iinclude

[env:{b.pio_board}]
platform = {b.pio_platform}
board = {b.pio_board}
framework = {b.pio_framework}
monitor_speed = 115200
build_flags =
    -std=gnu++17
    -Wall
    -Wextra
    -Iinclude
"""


def _render_pin_config_hpp(spec: EmbeddedProjectSpec, blueprint: HardwareBlueprint) -> str:
    consts: list[str] = []
    init_lines: list[str] = []

    for a in blueprint.pin_assignments:
        macro = f"PIN_{_c_ident(a.instance_id)}_{_c_ident(a.signal_name)}"
        consts.append(f"constexpr int {macro} = {a.gpio_num};  // {a.pin_id} ({a.bus_type})")
        if a.bus_type in ("GPIO", "PWM", "MOTOR_DRIVER") and "IN" not in a.signal_name[:4] or a.signal_name.startswith("IN"):
            if a.signal_name in ("ECHO", "SD", "MISO"):
                init_lines.append(f"    pinMode({macro}, INPUT);")
            elif a.bus_type in ("GPIO", "PWM", "MOTOR_DRIVER"):
                init_lines.append(f"    pinMode({macro}, OUTPUT);")

    consts_block = "\n".join(consts)
    init_block = "\n".join(init_lines) if init_lines else "    // Bus pins configured by peripheral drivers"

    period_ms = max(5, int(round(1000.0 / spec.control.loop_hz)))
    arch_cpp = ARCHETYPE_ENUM_MAP[spec.control.archetype]

    return f"""#pragma once
#include <stdint.h>
#include "controller_core.hpp"
#include "hal.hpp"

#ifdef ARDUINO
#include <Arduino.h>
#endif

namespace pin_config {{

{consts_block}

inline ehil::ControllerConfig default_controller_config() {{
    return ehil::ControllerConfig{{
        {arch_cpp},
        {period_ms}u,
        {spec.control.setpoint:.2f}f,
        {spec.control.kp:.3f}f,
        {spec.control.ki:.3f}f,
        {spec.control.kd:.3f}f,
        {spec.control.max_continuous_on_ms}u,
        {spec.control.sensor_timeout_ms}u,
        {spec.control.obstacle_stop_cm:.2f}f
    }};
}}

#ifdef ARDUINO
inline void init_pins() {{
{init_block}
}}

inline ehil::SensorReading sample_hardware_sensors() {{
    // Hardware bus read hook (I2C SHT31 / Ultrasonic pulseIn / I2S DMA RMS)
    return ehil::SensorReading{{{spec.control.setpoint:.2f}f, 25.0f, true}};
}}

inline void apply_hardware_actuators(const ehil::ActuatorCommand& cmd) {{
    (void)cmd;
}}
#endif

}}  // namespace pin_config
"""


def _render_main_cpp() -> str:
    return """#include "controller_core.hpp"
#include "pin_config.hpp"

#ifdef ARDUINO
#include "hal_mcu.hpp"

namespace {
ehil::McuHardwareHal g_hal;
ehil::ControllerCore g_core(g_hal, pin_config::default_controller_config());
}  // namespace

void setup() {
    g_hal.begin();
    g_core.init(g_hal.millis_now());
}

void loop() {
    g_core.tick(g_hal.millis_now());
}

#else
#include "hal_native_hil.hpp"

int main() {
    ehil::NativeHilHal hal;
    ehil::ControllerCore core(hal, pin_config::default_controller_config());
    hal.run_stdio_loop(core);
    return 0;
}
#endif
"""


def synthesize_firmware_project(
    spec: EmbeddedProjectSpec,
    blueprint: HardwareBlueprint,
    output_root: Path,
) -> Path:
    """Emit complete PlatformIO project directory (`platformio.ini`, `include/`, `src/`, `test/`)."""
    proj_dir = output_root / spec.project_id
    inc_dir = proj_dir / "include"
    src_dir = proj_dir / "src"
    test_dir = proj_dir / "test" / "test_controller"

    inc_dir.mkdir(parents=True, exist_ok=True)
    src_dir.mkdir(parents=True, exist_ok=True)
    test_dir.mkdir(parents=True, exist_ok=True)

    (proj_dir / "platformio.ini").write_text(_render_platformio_ini(blueprint), encoding="utf-8")
    (inc_dir / "pin_config.hpp").write_text(_render_pin_config_hpp(spec, blueprint), encoding="utf-8")

    shutil.copyfile(_TEMPLATES_DIR / "crc16.hpp", inc_dir / "crc16.hpp")
    shutil.copyfile(_TEMPLATES_DIR / "hal.hpp", inc_dir / "hal.hpp")
    shutil.copyfile(_TEMPLATES_DIR / "controller_core.hpp", inc_dir / "controller_core.hpp")

    shutil.copyfile(_TEMPLATES_DIR / "controller_core.cpp", src_dir / "controller_core.cpp")
    shutil.copyfile(_TEMPLATES_DIR / "hal_native_hil.hpp", src_dir / "hal_native_hil.hpp")
    shutil.copyfile(_TEMPLATES_DIR / "hal_mcu.hpp", src_dir / "hal_mcu.hpp")
    (src_dir / "main.cpp").write_text(_render_main_cpp(), encoding="utf-8")

    shutil.copyfile(_TEMPLATES_DIR / "test_main.cpp", test_dir / "test_main.cpp")
    return proj_dir
